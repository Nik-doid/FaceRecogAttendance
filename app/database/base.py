"""Declarative base and shared SQLAlchemy conventions.

A single naming convention keeps all auto-generated constraint names deterministic,
which matters for Alembic autogenerate diffs and for consistent rollback behaviour.
"""

from __future__ import annotations

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Base class for all ORM models owned by this service."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)
